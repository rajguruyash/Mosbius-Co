'use strict';

/**
 * Export the procedural cast as PNG files for the landing page.
 *
 * The app draws every character from the recipes in portraitArt.ts at run time,
 * so there were no image files to put on a web page. This script asks that same
 * module for the same RGBA buffers it hands the canvas, and encodes them as PNG.
 * It does not redraw, recolor or restyle anything: change a recipe and re-run,
 * and the exported assets follow.
 *
 *   node tools/export-sprites.cjs            → website/assets/cast + manifest
 *   node tools/export-sprites.cjs --sheet    → also a contact sheet for review
 *
 * Scale is an integer nearest-neighbour multiply (no interpolation, ever), so
 * the pixels stay square even if a browser ignores image-rendering: pixelated.
 */

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const loadTs = require('../test/load-ts.cjs');

const art = loadTs('src/renderer/src/scene/office/portraitArt.ts');
const { PORTRAIT_NAMES, PORTRAIT_W, PORTRAIT_H, SCENE_W, SCENE_H, portraitBuf, poseBuf } = art;

const SCALE = 4;
const POSES = ['idle', 'walk-a', 'walk-b', 'talk', 'wave', 'work', 'cheer', 'blink', 'back'];
const OUT = path.resolve(__dirname, '..', 'website/assets/cast');

// ─── PNG encoding (no dependencies: a PNG is a header plus deflated rows) ────

const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = -1;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

/** Encode RGBA bytes as a PNG. Colour type 6 (RGBA), 8 bits, no interlace. */
function encodePng(rgba, w, h) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;   // bit depth
  ihdr[9] = 6;   // RGBA
  // 10..12: deflate, no filter, no interlace — all zero already.

  // One filter byte (0 = none) in front of each row. Pixel art compresses
  // well enough flat that a filter pass would only cost time.
  const stride = w * 4;
  const raw = Buffer.alloc((stride + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (stride + 1)] = 0;
    Buffer.from(rgba.buffer ?? rgba, rgba.byteOffset ?? 0, rgba.length)
      .copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/** Integer nearest-neighbour upscale: every source pixel becomes a k×k block. */
function upscale(src, w, h, k) {
  if (k === 1) return src;
  const out = new Uint8ClampedArray(w * k * h * k * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const si = (y * w + x) * 4;
      for (let dy = 0; dy < k; dy++) {
        for (let dx = 0; dx < k; dx++) {
          const di = ((y * k + dy) * w * k + x * k + dx) * 4;
          out[di] = src[si]; out[di + 1] = src[si + 1];
          out[di + 2] = src[si + 2]; out[di + 3] = src[si + 3];
        }
      }
    }
  }
  return out;
}

function writePng(file, buf, w, h) {
  const png = encodePng(upscale(buf, w, h, SCALE), w * SCALE, h * SCALE);
  fs.writeFileSync(file, png);
  return png.length;
}

// ─── export ─────────────────────────────────────────────────────────────────

fs.mkdirSync(OUT, { recursive: true });

let files = 0;
let bytes = 0;
const manifest = {
  note: 'Generated by tools/export-sprites.cjs from src/renderer/src/scene/office/portraitArt.ts. Do not hand-edit.',
  generated: new Date().toISOString().slice(0, 10),
  scale: SCALE,
  frame: { w: SCENE_W * SCALE, h: SCENE_H * SCALE },
  portrait: { w: PORTRAIT_W * SCALE, h: PORTRAIT_H * SCALE },
  poses: POSES,
  characters: {},
};

for (const name of PORTRAIT_NAMES) {
  const dir = path.join(OUT, name);
  fs.mkdirSync(dir, { recursive: true });
  const entry = {};

  bytes += writePng(path.join(dir, 'portrait.png'), portraitBuf(name), PORTRAIT_W, PORTRAIT_H);
  entry.portrait = `assets/cast/${name}/portrait.png`;
  files++;

  for (const pose of POSES) {
    bytes += writePng(path.join(dir, `${pose}.png`), poseBuf(name, pose), SCENE_W, SCENE_H);
    entry[pose] = `assets/cast/${name}/${pose}.png`;
    files++;
  }
  manifest.characters[name] = entry;
}

// ─── atlas ──────────────────────────────────────────────────────────────────
// The individual files above are the deliverable; the page does not load 300 of
// them. Everything also goes into one 1× atlas (one request, a few KB) that the
// scene engine blits from with smoothing off — which is why the atlas is NOT
// upscaled: a canvas drawing it at an integer scale stays exactly as crisp, and
// a 4× atlas would be 16× the bytes for no gain.
{
  const cols = POSES.length + 1;             // + the portrait column
  const cellW = SCENE_W, cellH = SCENE_H;
  const W = cols * cellW, H = PORTRAIT_NAMES.length * cellH;
  const atlas = new Uint8ClampedArray(W * H * 4);
  const blit = (src, sw, sh, ox, oy) => {
    for (let y = 0; y < sh; y++) {
      for (let x = 0; x < sw; x++) {
        const si = (y * sw + x) * 4;
        const di = ((oy + y) * W + ox + x) * 4;
        atlas[di] = src[si]; atlas[di + 1] = src[si + 1];
        atlas[di + 2] = src[si + 2]; atlas[di + 3] = src[si + 3];
      }
    }
  };
  PORTRAIT_NAMES.forEach((name, row) => {
    POSES.forEach((pose, col) => blit(poseBuf(name, pose), SCENE_W, SCENE_H, col * cellW, row * cellH));
    // Portraits are shorter than a cell; bottom-align so the shoulders meet the floor line.
    blit(portraitBuf(name), PORTRAIT_W, PORTRAIT_H, POSES.length * cellW, row * cellH + (cellH - PORTRAIT_H));
  });
  const atlasFile = path.resolve(__dirname, '..', 'website/assets/cast-atlas.png');
  const png = encodePng(atlas, W, H);
  fs.writeFileSync(atlasFile, png);
  manifest.atlas = {
    file: 'assets/cast-atlas.png',
    scale: 1,
    cell: { w: cellW, h: cellH },
    cols,
    // Column index per pose, plus where the portrait sits inside its own cell.
    columns: Object.fromEntries(POSES.map((p, i) => [p, i])),
    portraitColumn: POSES.length,
    portraitInset: { x: 0, y: cellH - PORTRAIT_H, w: PORTRAIT_W, h: PORTRAIT_H },
    rows: Object.fromEntries(PORTRAIT_NAMES.map((n, i) => [n, i])),
  };
  console.log(`atlas: ${atlasFile} ${W}×${H}, ${(png.length / 1024).toFixed(1)} KB`);
}

fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

// The same atlas map as a plain script. The page reads it from a <script> tag
// rather than fetch()ing the JSON, so index.html also works when it is opened
// straight off disk (file://), where fetch is blocked by the origin rules.
fs.writeFileSync(
  path.resolve(__dirname, '..', 'website/js/cast-manifest.js'),
  '/* Generated by tools/export-sprites.cjs. Do not hand-edit. */\n' +
  `window.CAST_ATLAS = ${JSON.stringify(manifest.atlas, null, 2)};\n`
);

// A single sheet of every character in every pose, for eyeballing the result.
if (process.argv.includes('--sheet')) {
  const cols = POSES.length + 1;
  const rows = PORTRAIT_NAMES.length;
  const cw = SCENE_W + 2, ch = SCENE_H + 2;
  const W = cols * cw, H = rows * ch;
  const sheet = new Uint8ClampedArray(W * H * 4);
  for (let i = 0; i < W * H; i++) { sheet[i * 4] = 24; sheet[i * 4 + 1] = 28; sheet[i * 4 + 2] = 38; sheet[i * 4 + 3] = 255; }
  const blit = (src, sw, sh, ox, oy) => {
    for (let y = 0; y < sh; y++) for (let x = 0; x < sw; x++) {
      const si = (y * sw + x) * 4;
      if (src[si + 3] === 0) continue;
      const di = ((oy + y) * W + ox + x) * 4;
      sheet[di] = src[si]; sheet[di + 1] = src[si + 1]; sheet[di + 2] = src[si + 2]; sheet[di + 3] = 255;
    }
  };
  PORTRAIT_NAMES.forEach((name, r) => {
    blit(portraitBuf(name), PORTRAIT_W, PORTRAIT_H, 1, r * ch + 1 + (SCENE_H - PORTRAIT_H));
    POSES.forEach((pose, c) => blit(poseBuf(name, pose), SCENE_W, SCENE_H, (c + 1) * cw + 1, r * ch + 1));
  });
  const out = path.resolve(__dirname, '..', 'website/assets/cast-sheet.png');
  fs.writeFileSync(out, encodePng(upscale(sheet, W, H, 3), W * 3, H * 3));
  console.log(`sheet: ${out}`);
}

console.log(`${PORTRAIT_NAMES.length} characters, ${files} PNGs, ${(bytes / 1024).toFixed(0)} KB total`);
console.log(`frames ${SCENE_W * SCALE}×${SCENE_H * SCALE}, portraits ${PORTRAIT_W * SCALE}×${PORTRAIT_H * SCALE} (${SCALE}× nearest-neighbour)`);
