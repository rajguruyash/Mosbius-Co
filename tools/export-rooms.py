#!/usr/bin/env python3
"""Export each location of the painted world as a PNG for the landing page.

The app's eight rooms already exist as real pixel art: tools/himym paints one
293x22-tile world, and export.py writes it as world-bg.png plus an occluder
atlas. The website should show those exact rooms, not new ones drawn to look
like them, so this crops each location out of that world and flattens the
occluders that belong to it into the crop.

It reads the built assets only. It paints nothing and changes nothing in
tools/himym or in the app.

    python3 tools/export-rooms.py

Writes website/assets/rooms/<location>.png (544x352 each) and rooms.json with
each room's label, floor line and the doorway, so the scene engine can walk a
character to a sensible place without hard-coding pixel positions in JS.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src/renderer/src/assets/himym')
OUT = os.path.join(ROOT, 'website/assets/rooms')

# Where the floor is, as a fraction of room height, and a one-line description.
# Both are editorial, so they live here rather than being guessed in JavaScript.
ROOMS = {
    'apartment': ("Ted's Place", 'The apartment above the bar. Red couch, yellow umbrella by the door.'),
    'maclarens': ("MacLaren's Pub", 'The booth downstairs. Carl is behind the bar.'),
    'gnb': ('GNB', 'Goliath National Bank. Desks, monitors and a boardroom nobody books.'),
    'rooftop': ('The Rooftop', 'Above it all, with the skyline going on without you.'),
    'barney': ("Barney's Place", 'Immaculate, suspicious, and entirely open plan.'),
    'columbia': ('Columbia', 'The lecture hall. Twenty-nine seats and one architect.'),
    'lasertag': ('Laser Tag', 'Neon, smoke and a scoreboard. Strategy optional.'),
}


def main() -> int:
    meta = json.load(open(os.path.join(SRC, 'world.json'), encoding='utf-8'))
    tile = meta['tile']
    bg = Image.open(os.path.join(SRC, 'world-bg.png')).convert('RGBA')
    ov = Image.open(os.path.join(SRC, 'world-ov.png')).convert('RGBA')

    os.makedirs(OUT, exist_ok=True)
    index = {'note': 'Generated by tools/export-rooms.py. Do not hand-edit.',
             'tile': tile, 'rooms': {}}

    for name, loc in meta['locations'].items():
        if name not in ROOMS:
            print(f'skipping unlisted location {name}', file=sys.stderr)
            continue
        x0, y0 = loc['x'] * tile, loc['y'] * tile
        w, h = loc['w'] * tile, loc['h'] * tile
        room = bg.crop((x0, y0, x0 + w, y0 + h)).copy()

        # Flatten this room's occluders (furniture drawn over characters in the
        # app) back into the still image, nearest ones last.
        for piece in sorted(meta['occluders'], key=lambda p: p['base']):
            px, py, pw, ph = piece['x'], piece['y'], piece['w'], piece['h']
            if not (x0 <= px < x0 + w and y0 <= py < y0 + h):
                continue
            sprite = ov.crop((piece['ax'], piece['ay'], piece['ax'] + pw, piece['ay'] + ph))
            room.alpha_composite(sprite, (px - x0, py - y0))

        room.save(os.path.join(OUT, f'{name}.png'))

        # Seats, in room-local pixels. The app walks characters to these; the
        # page uses them to stand characters somewhere the furniture actually
        # is, and to light the exact screen rectangle the painter drew.
        seats = []
        for s in meta.get('seats', []):
            sx, sy = s['x'] * tile, s['y'] * tile
            if not (x0 <= sx < x0 + w and y0 <= sy < y0 + h):
                continue
            seat = {'name': s['name'], 'x': sx - x0, 'y': sy - y0, 'facing': s.get('facing', 'up')}
            scr = s.get('screen')
            if scr:
                seat['screen'] = {'x': scr['x'] - x0, 'y': scr['y'] - y0, 'w': scr['w'], 'h': scr['h']}
            seats.append(seat)

        label, blurb = ROOMS[name]
        door = loc.get('door', {})
        index['rooms'][name] = {
            'seats': seats,
            'label': label,
            'blurb': blurb,
            'file': f'assets/rooms/{name}.png',
            'w': w, 'h': h,
            # door in room-local pixels, clamped inside the crop
            'door': {'x': max(0, min(w - tile, door.get('x', 0) * tile - x0)),
                     'y': max(0, min(h - tile, door.get('y', 0) * tile - y0))},
        }
        print(f'{name:10s} {w}x{h}')

    # The street outside (MacLaren's facade, sidewalk, road), the skyline strip
    # and the cab are painted the same way and used as-is by the hero scene.
    scene_out = os.path.join(ROOT, 'website/assets/scene')
    os.makedirs(scene_out, exist_ok=True)
    for f in ('street.png', 'street-ov.png', 'skyline.png', 'cab.png'):
        im = Image.open(os.path.join(SRC, f)).convert('RGBA')
        im.save(os.path.join(scene_out, f))
        index.setdefault('scene', {})[f[:-4]] = {'file': f'assets/scene/{f}', 'w': im.width, 'h': im.height}
        print(f'{f:12s} {im.width}x{im.height}')

    # The street elevation's anchors: the pub door and the steps down to it, the stoop
    # up the right-hand side, and Ted's door at the top of it. The page walks
    # characters to these rather than guessing pixel positions.
    anchors = os.path.join(SRC, 'street.json')
    if os.path.exists(anchors):
        index['street'] = json.load(open(anchors, encoding='utf-8'))
        print('street.json  anchors')

    json.dump(index, open(os.path.join(OUT, 'rooms.json'), 'w', encoding='utf-8'), indent=2)
    # Same data as a plain script, so index.html also works opened off disk,
    # where fetch() of a local JSON file is blocked.
    js = os.path.join(ROOT, 'website/js/rooms-manifest.js')
    os.makedirs(os.path.dirname(js), exist_ok=True)
    with open(js, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/export-rooms.py. Do not hand-edit. */\n')
        fh.write('window.ROOMS = ' + json.dumps(index, indent=2) + ';\n')
    print(f'{len(index["rooms"])} rooms -> {OUT}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
