#!/usr/bin/env node
'use strict';

/**
 * Writes the two support tables in INTEGRATIONS.md from the data the app itself uses
 * (src/shared/providers.ts and src/shared/agentCompat.ts), so the document cannot say something the app does not.
 *
 *   node tools/gen-support-matrix.cjs          rewrite the block between the markers in INTEGRATIONS.md
 *   node tools/gen-support-matrix.cjs --check  exit 1 if INTEGRATIONS.md is not what the data says (the test uses this)
 */
const fs = require('node:fs');
const path = require('node:path');
const loadTs = require('../test/load-ts.cjs');

const ROOT = path.resolve(__dirname, '..');
const FILE = path.join(ROOT, 'INTEGRATIONS.md');
const START = '<!-- support-matrix:start (generated by tools/gen-support-matrix.cjs; do not edit by hand) -->';
const END = '<!-- support-matrix:end -->';

const { PROVIDERS } = loadTs('src/shared/providers.ts');
const { flagsOf, TERMS } = require('./lib/catalogue.cjs');
const { MARK, legendMd } = require('./lib/render.cjs');
const { AGENT_COMPAT } = loadTs('src/shared/agentCompat.ts');
const en = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/renderer/src/i18n/locales/en.json'), 'utf8'));

const WAY = { account: 'sign in with your account', device: 'sign-in code', 'own-app': 'an app you register', key: 'a key you create', local: 'runs on this computer', engine: 'AI engines settings' };
const STATUS = { verified: 'VERIFIED', limited: 'PARTLY VERIFIED', untested: 'UNVERIFIED', planned: 'NOT IMPLEMENTED', na: 'NOT APPLICABLE' };
const CAT = en.hub.cat;
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function providerTable() {
  const rows = ['| Provider | Group | What an agent can do | Connects by | Status | Locally tested | Stand-in tested | Real-account verified | What was checked |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |'];
  for (const p of PROVIDERS) {
    const v = p.verification;
    const checked = `${v.note}${v.evidence ? ` Evidence: \`${v.evidence}\`${v.on ? ` (${v.on})` : ''}.` : ''}`;
    // the AI engine keys are not integrations: the three columns do not apply to them
    const f = p.category === 'ai' ? { locallyTested: 'na', standInTested: 'na', realAccountVerified: 'na' } : flagsOf(p);
    rows.push(`| ${cell(p.label)} | ${cell(CAT[p.category] ?? p.category)} | ${cell(en.hub.providers[p.id] ?? '')} | ${cell(p.ways.map((w) => WAY[w] ?? w).join(', ') || 'not available yet')} | **${STATUS[v.status] ?? v.status}** | ${MARK[f.locallyTested]} | ${MARK[f.standInTested]} | ${MARK[f.realAccountVerified]} | ${cell(checked)} |`);
  }
  return rows.join('\n');
}

function agentTable() {
  const SUP = { verified: 'VERIFIED', wired: 'WIRED, NOT RUN', unsupported: 'NOT SUPPORTED' };
  const DELIVERY = { 'config-file': 'a config file the agent may not read', 'command-line-and-env': 'the broker address on the command line, the pass in one variable', 'settings-file-and-env': 'a settings file naming one variable, the pass in that variable' };
  const SHELL = { yes: 'hidden from the agent\'s shell', no: 'visible to the agent\'s shell', unknown: 'not measured' };
  const rows = ['| CLI | Integrations | How it is handed the pass | The pass and the agent\'s shell | Skills | Skills folders | Evidence |', '| --- | --- | --- | --- | --- | --- | --- |'];
  for (const a of AGENT_COMPAT) {
    const ev = [...new Set([...a.integrationsEvidence, ...a.skillsEvidence])].map((e) => `\`${e}\``).join(', ') || 'none: not run';
    rows.push(`| ${a.label} | **${SUP[a.integrations]}** | ${DELIVERY[a.delivery]} | ${SHELL[a.capabilityHiddenFromShell]}${a.shellProtectionNeedsSandbox ? ', only while its OS sandbox is on' : ''} | **${SUP[a.skills]}** | ${a.skillFolders.map((f) => `\`${f}\``).join(', ')} | ${ev} |`);
  }
  return rows.join('\n');
}

const block = `${START}\n\n### What the words mean\n\n${legendMd({ terms: TERMS })}\n\nThe Status column uses the app's own status words in capitals: VERIFIED is *Locally tested* (the card in Settings says "Verified"), PARTLY VERIFIED is *Partly tested locally*, UNVERIFIED is *Stand-in tested, not yet verified* (the card says "Not yet tested"), NOT IMPLEMENTED is the card's "Planned", and NOT APPLICABLE is for the AI engine keys, which are not integrations.\n\n### Providers\n\n${providerTable()}\n\n### Agent CLIs\n\n${agentTable()}\n\n${END}`;

if (!fs.existsSync(FILE)) { console.error(`${FILE} does not exist yet; create it with the two markers first`); process.exit(2); }
const text = fs.readFileSync(FILE, 'utf8');
const a = text.indexOf(START); const b = text.indexOf(END);
if (a < 0 || b < a) { console.error('INTEGRATIONS.md has no support-matrix markers'); process.exit(2); }
const next = text.slice(0, a) + block + text.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('INTEGRATIONS.md is out of date: run `node tools/gen-support-matrix.cjs`'); process.exit(1); }
  console.log('INTEGRATIONS.md matches the app\'s own data'); process.exit(0);
}
fs.writeFileSync(FILE, next);
console.log(`rewrote the support matrix in INTEGRATIONS.md (${PROVIDERS.length} providers, ${AGENT_COMPAT.length} CLIs)`);
